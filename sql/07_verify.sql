   07. 검증 / 대사 쿼리   바인드: :RUN_ID
   ===================================================================== */

-- V1. 점 × 컴포넌트 합계 (고객 사인오프용 요약표)
SELECT C.STOR_CD, C.ITEM_TYPE, C.STOC_TYPE, C.COMP_TYPE,
       COUNT(*) ROW_CNT, COUNT(DISTINCT C.SRC_BILL_NO) BILL_CNT, SUM(C.SIGN * C.QTY) SIGNED_QTY
  FROM MIG_STOC_COMP C
 WHERE C.MIG_RUN_ID = :RUN_ID
 GROUP BY ROLLUP (C.STOR_CD, C.ITEM_TYPE, C.STOC_TYPE, C.COMP_TYPE)
 ORDER BY 1,2,3,4;

-- V2. 음수 재고 (0건이어야 함)
SELECT * FROM MIG_BASE_STOC WHERE MIG_RUN_ID = :RUN_ID AND QTY < 0 ORDER BY QTY;

-- V2-1. 음수 원인 추적: 해당 창고·상품의 컴포넌트 내역
SELECT C.* FROM MIG_STOC_COMP C
 WHERE C.MIG_RUN_ID = :RUN_ID
   AND (C.STOR_CD, C.GOOS_CD) IN (SELECT M.STOR_CD, B.GOOS_CD
                                    FROM MIG_BASE_STOC B JOIN MIG_MAP_STOR M ON M.NEW_WH_CD = B.NEW_WH_CD
                                   WHERE B.MIG_RUN_ID = :RUN_ID AND B.QTY < 0)
 ORDER BY C.GOOS_CD, C.COMP_TYPE;

-- V3. 매핑 누락: 최종 GOOS_CD 미설정 / 점 매핑 없음
SELECT 'NO_GOOS' GBN, COUNT(*) FROM MIG_STOC_COMP WHERE MIG_RUN_ID = :RUN_ID AND GOOS_CD IS NULL
UNION ALL
SELECT 'NO_STOR_MAP', COUNT(*) FROM MIG_STOC_COMP C
 WHERE C.MIG_RUN_ID = :RUN_ID
   AND NOT EXISTS (SELECT 1 FROM MIG_MAP_STOR M WHERE M.COMP_CD = C.COMP_CD AND M.STOR_CD = C.STOR_CD)
UNION ALL
SELECT 'OLD_CODE_LEFT', COUNT(*) FROM MIG_STOC_COMP C
 WHERE C.MIG_RUN_ID = :RUN_ID AND EXISTS (SELECT 1 FROM MIG_MAP_GOOS G WHERE G.OLD_GOOS_CD = C.GOOS_CD);
-- + 신규 시스템 상품마스터 미존재 코드 (타겟 마스터 테이블명 확인 후 추가)

-- V4. 동일 매출라인이 같은 컴포넌트에 중복 적재 (0건이어야 함)
SELECT COMP_TYPE, ITEM_TYPE, SRC_KEY, COUNT(*) CNT
  FROM MIG_STOC_COMP
 WHERE MIG_RUN_ID = :RUN_ID AND COMP_TYPE IN ('C03','C04','C05')
 GROUP BY COMP_TYPE, ITEM_TYPE, SRC_KEY HAVING COUNT(*) > 1;

-- V5. H재반입(C04)·미인도(C05) 양쪽에 동시에 걸린 빌 (업무적으로 가능한지 확인)
SELECT SRC_BILL_NO FROM MIG_STOC_COMP WHERE MIG_RUN_ID = :RUN_ID AND COMP_TYPE = 'C04'
INTERSECT
SELECT SRC_BILL_NO FROM MIG_STOC_COMP WHERE MIG_RUN_ID = :RUN_ID AND COMP_TYPE = 'C05';

-- V6. 차감(C04/C05) 대상 중 교환권(C03)에 없는 빌 비율 — Q1 해석 검증용
SELECT C.COMP_TYPE, COUNT(DISTINCT C.SRC_BILL_NO) BILL_CNT,
       COUNT(DISTINCT CASE WHEN X.SRC_BILL_NO IS NULL THEN C.SRC_BILL_NO END) NOT_IN_C03
  FROM MIG_STOC_COMP C
  LEFT JOIN (SELECT DISTINCT SRC_BILL_NO FROM MIG_STOC_COMP WHERE MIG_RUN_ID = :RUN_ID AND COMP_TYPE = 'C03') X
    ON X.SRC_BILL_NO = C.SRC_BILL_NO
 WHERE C.MIG_RUN_ID = :RUN_ID AND C.COMP_TYPE IN ('C04','C05')
 GROUP BY C.COMP_TYPE;

-- V7. 리허설 회차 비교 (예: R1 vs R2)
SELECT NVL(A.NEW_WH_CD, B.NEW_WH_CD) WH, NVL(A.GOOS_CD, B.GOOS_CD) GOOS_CD,
       NVL(A.ITEM_TYPE, B.ITEM_TYPE) ITEM_TYPE, NVL(A.STOC_TYPE, B.STOC_TYPE) STOC_TYPE,
       NVL(A.QTY,0) PREV_QTY, NVL(B.QTY,0) CURR_QTY, NVL(B.QTY,0) - NVL(A.QTY,0) DIFF
  FROM (SELECT * FROM MIG_BASE_STOC WHERE MIG_RUN_ID = :PREV_RUN_ID) A
  FULL OUTER JOIN (SELECT * FROM MIG_BASE_STOC WHERE MIG_RUN_ID = :RUN_ID) B
    ON A.COMP_CD = B.COMP_CD AND A.NEW_WH_CD = B.NEW_WH_CD AND A.ITEM_TYPE = B.ITEM_TYPE
   AND A.STOC_TYPE = B.STOC_TYPE AND A.GOOS_CD = B.GOOS_CD
 WHERE NVL(A.QTY,0) <> NVL(B.QTY,0)
 ORDER BY ABS(NVL(B.QTY,0) - NVL(A.QTY,0)) DESC;
